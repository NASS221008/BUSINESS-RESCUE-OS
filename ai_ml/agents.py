
"""
AI/ML agents for Business Rescue OS.

Four Groq-powered agents:
1. Sales Agent
2. Inventory Agent
3. Finance Agent
4. Strategy Agent

Web Research Agent:
- Uses DuckDuckGo through the free ddgs package.
- Can optionally use Tavily if TAVILY_API_KEY is available.

Every Groq response is parsed as JSON.
Every agent has a safe fallback so one failed call
does not crash the complete demo pipeline.

run_pipeline(problem_id) is the single public function
the backend should call.
"""

