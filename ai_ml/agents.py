GROQ_MODEL = os.environ.get("GROQ_MODEL", "openai/gpt-oss-120b")


_client = None


# --------------------------------------------------------------------------
# Groq Client
# --------------------------------------------------------------------------

def get_client():
    """
    Create and cache the Groq client.
    """

    global _client

    if _client is None:

        api_key = os.environ.get("GROQ_API_KEY")

        if not api_key:
            raise RuntimeError(
                "GROQ_API_KEY environment variable is not set."
            )

        from groq import Groq

        _client = Groq(
            api_key=api_key
        )

    return _client


# --------------------------------------------------------------------------
# Groq JSON Helper
# --------------------------------------------------------------------------

def _call_groq_json(system_prompt: str, user_content: str) -> dict:
    """
    Call Groq and return a parsed JSON dictionary.
    """

    client = get_client()

    response = client.chat.completions.create(
        model=GROQ_MODEL,
        messages=[
            {
                "role": "system",
                "content": system_prompt
            },
            {
                "role": "user",
                "content": user_content
            }
        ],
        temperature=0.2,
        response_format={
            "type": "json_object"
        }
    )

    content = response.choices[0].message.content

    result = json.loads(content)

    if not isinstance(result, dict):
        raise ValueError(
            "Groq response was not a JSON object."
        )

    return result


# --------------------------------------------------------------------------
# Sales Agent
# --------------------------------------------------------------------------

def sales_agent(problem_data: dict) -> dict:
    """
    Estimate realistic demand/sell-through for the units at risk.
    """

    system_prompt = """
You are the Sales Agent.

Single responsibility:
Estimate realistic sell-through for the units at risk based only on the
provided business problem.

Use the exact units_at_risk and value_at_risk from the database.
Do not invent or modify those numbers.

All financial amounts are in INR (Indian Rupees).

estimated_units_sold must not exceed units_at_risk.

Return ONLY valid JSON matching this schema:

{
  "sell_through_estimate_pct": "number",
  "estimated_units_sold": "number",
  "sales_reason": "string"
}
"""

    user_content = json.dumps(
        problem_data
    )

    try:

        result = _call_groq_json(
            system_prompt,
            user_content
        )

        # Basic safety checks on the LLM response.
        units_at_risk = int(
            problem_data["units_at_risk"]
        )

        sell_through = float(
            result.get(
                "sell_through_estimate_pct",
                0
            )
        )

        estimated_units = int(
            result.get(
                "estimated_units_sold",
                0
            )
        )

        sell_through = max(
            0,
            min(100, sell_through)
        )

        estimated_units = max(
            0,
            min(units_at_risk, estimated_units)
        )

        result["sell_through_estimate_pct"] = sell_through
        result["estimated_units_sold"] = estimated_units
        result["sales_reason"] = str(
            result.get(
                "sales_reason",
                "Sales assessment generated by the Sales Agent."
            )
        )

        return result

    except Exception as e:

        print(
            f"[Sales Agent] Groq failed. Using fallback: {e}"
        )

        units = int(
            problem_data["units_at_risk"]
        )

        estimated_units = round(
            units * 0.40
        )

        return {
            "sell_through_estimate_pct": 40,
            "estimated_units_sold": estimated_units,
            "sales_reason": (
                "Fallback estimate because the Sales Agent "
                "was unavailable."
            )
        }


