# Inventory Agent
# --------------------------------------------------------------------------

def inventory_agent(problem_data: dict) -> dict:
    """
    Assess stock distribution and identify whether transfer is a candidate.
    """

    system_prompt = """
You are the Inventory Agent.

Single responsibility:
Assess how the at-risk stock should be distributed across branches and
flag whether transferring stock to a higher-demand branch is a candidate.

Use only the provided data.

Use the exact units_at_risk and value_at_risk from the database.
Do not invent or modify those numbers.

If branch-level data is not provided, clearly state that branch information
is unavailable. Do not invent a specific branch name.

Return ONLY valid JSON matching this schema:

{
  "inventory_issue": "string",
  "transfer_recommended": "boolean",
  "transfer_candidate": "string",
  "inventory_notes": "string"
}
"""

    user_content = json.dumps(
        problem_data
    )

    try:

        result = _call_groq_json(
            system_prompt,
            user_content
        )

        transfer_recommended = result.get(
            "transfer_recommended",
            False
        )

        if not isinstance(
            transfer_recommended,
            bool
        ):
            transfer_recommended = False

        result["inventory_issue"] = str(
            result.get(
                "inventory_issue",
                "Inventory assessment generated by the Inventory Agent."
            )
        )

        result["transfer_recommended"] = (
            transfer_recommended
        )

        result["transfer_candidate"] = str(
            result.get(
                "transfer_candidate",
                ""
            )
        )

        result["inventory_notes"] = str(
            result.get(
                "inventory_notes",
                ""
            )
        )

        return result

    except Exception as e:

        print(
            f"[Inventory Agent] Groq failed. Using fallback: {e}"
        )

        return {
            "inventory_issue": (
                "Excess inventory requires redistribution."
            ),
            "transfer_recommended": False,
            "transfer_candidate": (
                "Branch data unavailable"
            ),
            "inventory_notes": (
                "Fallback assessment because the Inventory Agent "
                "was unavailable."
            )
        }


# --------------------------------------------------------------------------
# Finance Agent
# --------------------------------------------------------------------------

def finance_agent(
    problem_data: dict,
    sales_result: dict,
    inventory_result: dict
) -> dict:
    """
    Convert sales and inventory assessments into financial risk
    and expected-value numbers.
    """

    system_prompt = """
You are the Finance Agent.

Single responsibility:
Turn the business problem, sales assessment, and inventory assessment into
financial risk and expected-value estimates.

Use the exact units_at_risk and value_at_risk from the database.
Do not change those values.

All financial amounts are in INR (Indian Rupees).

Use the Sales Agent's estimated_units_sold as an important input when
estimating expected recovery.

The expected_recovery must be a number no greater than value_at_risk.

The remaining_risk must equal:

value_at_risk - expected_recovery

Return ONLY valid JSON matching this schema:

{
  "risk_level": "string",
  "expected_recovery": "number",
  "remaining_risk": "number",
  "finance_notes": "string"
}
"""

    user_content = json.dumps({
        "problem": problem_data,
        "sales_assessment": sales_result,
        "inventory_assessment": inventory_result
    })

    try:

        result = _call_groq_json(
            system_prompt,
            user_content
        )

        value_at_risk = float(
            problem_data["value_at_risk"]
        )

        expected_recovery = float(
            result.get(
                "expected_recovery",
                0
            )
        )

        expected_recovery = max(
            0,
            min(value_at_risk, expected_recovery)
        )

        remaining_risk = round(
            value_at_risk - expected_recovery,
            2
        )

        result["risk_level"] = str(
            result.get(
                "risk_level",
                "High"
            )
        )

        result["expected_recovery"] = round(
            expected_recovery,
            2
        )

        result["remaining_risk"] = remaining_risk

        result["finance_notes"] = str(
            result.get(
                "finance_notes",
                ""
            )
        )

        return result

    except Exception as e:

        print(
            f"[Finance Agent] Groq failed. Using fallback: {e}"
        )

        value_at_risk = float(
            problem_data["value_at_risk"]
        )

        sell_through_pct = sales_result.get(
            "sell_through_estimate_pct",
            40
        )

        try:
            sell_through_pct = float(
                sell_through_pct
            )
        except (
            TypeError,
            ValueError
        ):
            sell_through_pct = 40

        sell_through_pct = max(
            0,
            min(100, sell_through_pct)
        )

        expected_recovery = round(
            value_at_risk * (
                sell_through_pct / 100
            ),
            2
        )

        remaining_risk = round(
            value_at_risk - expected_recovery,
            2
        )

        return {
            "risk_level": "High",
            "expected_recovery": expected_recovery,
            "remaining_risk": remaining_risk,
            "finance_notes": (
                "Fallback financial estimate based on the Sales Agent "
                "sell-through estimate because the Finance Agent "
                "was unavailable."
            )
        }


